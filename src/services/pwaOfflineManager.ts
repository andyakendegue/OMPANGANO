import { useState, useEffect } from 'react';

const CACHE_NAME = 'ompagano-offline-v5';
const READY_STORAGE_KEY = 'ompagano_airplane_ready_v5';

export interface OfflineShellStatus {
  isReady: boolean;
  isWarmingUp: boolean;
  cachedAssetsCount: number;
}

type StatusListener = (status: OfflineShellStatus) => void;

let currentStatus: OfflineShellStatus = {
  isReady: typeof localStorage !== 'undefined' && localStorage.getItem(READY_STORAGE_KEY) === 'true',
  isWarmingUp: false,
  cachedAssetsCount: 0
};

const listeners = new Set<StatusListener>();

function updateStatus(partial: Partial<OfflineShellStatus>) {
  currentStatus = { ...currentStatus, ...partial };
  if (currentStatus.isReady) {
    try {
      localStorage.setItem(READY_STORAGE_KEY, 'true');
    } catch {}
  }
  listeners.forEach((cb) => {
    try {
      cb(currentStatus);
    } catch {}
  });
}

function resolveMimeType(url: string, response: Response): string {
  const headerType = response.headers.get('Content-Type');
  if (headerType) return headerType;
  const clean = url.split('?')[0].toLowerCase();
  if (clean.endsWith('.html') || clean === '/') return 'text/html; charset=utf-8';
  if (clean.endsWith('.js') || clean.endsWith('.mjs') || clean.endsWith('.ts') || clean.endsWith('.tsx')) {
    return 'application/javascript; charset=utf-8';
  }
  if (clean.endsWith('.css')) return 'text/css; charset=utf-8';
  if (clean.endsWith('.webmanifest') || clean.endsWith('.json')) return 'application/json; charset=utf-8';
  if (clean.endsWith('.svg')) return 'image/svg+xml';
  if (clean.endsWith('.png')) return 'image/png';
  if (clean.endsWith('.jpg') || clean.endsWith('.jpeg')) return 'image/jpeg';
  return 'application/octet-stream';
}

/**
 * Collects all same-origin asset URLs from the build manifest, DOM tags, and Resource Timing API
 */
async function collectAllAppAssetUrls(): Promise<string[]> {
  if (typeof window === 'undefined' || typeof document === 'undefined') return [];

  const urls = new Set<string>([
    '/',
    '/index.html',
    '/manifest.webmanifest',
    '/icon.svg',
    '/apple-touch-icon.png',
    '/pwa-192x192.png',
    '/pwa-512x512.png',
    '/pwa-maskable-512x512.png',
    '/assets/aistudio/LOGO-symbole_1c65e221.png',
    '/assets/aistudio/LOGO_c7de06c8.jpg'
  ]);

  // 1. Fetch build/dev manifest generated by `ompaganoUniversalOfflinePlugin`
  try {
    const res = await fetch('/__ompagano_manifest.json', {
      cache: 'no-cache',
      credentials: 'same-origin'
    });
    if (res && res.ok) {
      const data = await res.json();
      if (data && Array.isArray(data.assets)) {
        for (const asset of data.assets) {
          if (typeof asset === 'string' && asset) {
            urls.add(asset.startsWith('/') ? asset : '/' + asset);
          }
        }
      }
    }
  } catch {}

  try {
    // 2. DOM script, stylesheet link, and img tags
    document.querySelectorAll('script[src]').forEach((el) => {
      const src = (el as HTMLScriptElement).src;
      if (src) urls.add(src);
    });
    document.querySelectorAll('link[href]').forEach((el) => {
      const rel = ((el as HTMLLinkElement).rel || '').toLowerCase();
      const href = (el as HTMLLinkElement).href;
      if (href && rel !== 'preconnect' && rel !== 'dns-prefetch') {
        urls.add(href);
      }
    });
    document.querySelectorAll('img[src]').forEach((el) => {
      const src = (el as HTMLImageElement).src;
      if (src && !src.startsWith('data:') && !src.startsWith('blob:')) {
        urls.add(src);
      }
    });

    // 3. Performance Resource Timing entries
    if (typeof performance !== 'undefined' && typeof performance.getEntriesByType === 'function') {
      const resources = performance.getEntriesByType('resource') as PerformanceResourceTiming[];
      for (const res of resources) {
        if (!res.name) continue;
        if (res.name.startsWith(window.location.origin)) {
          if (
            !res.name.includes('version.json') &&
            !res.name.includes('__ompagano_manifest.json')
          ) {
            urls.add(res.name);
          }
        }
      }
    }
  } catch {}

  return Array.from(urls);
}

/**
 * Directly populates CacheStorage from the main thread AND coordinates with the Service Worker
 * so Firefox Desktop, Android Default Browser, and iOS Safari have 100% of assets cached after 1 visit.
 */
export async function warmUpOfflineShell(): Promise<void> {
  if (typeof window === 'undefined' || !('caches' in window)) return;
  if (!navigator.onLine) {
    try {
      const cache = await window.caches.open(CACHE_NAME);
      const hasShell = await cache.match('/index.html');
      if (hasShell) {
        updateStatus({ isReady: true, isWarmingUp: false });
      }
    } catch {}
    return;
  }

  updateStatus({ isWarmingUp: true });

  try {
    const cache = await window.caches.open(CACHE_NAME);

    // 1. Store clean non-redirected HTML shell under '/', '/index.html', and window.location.href
    try {
      const htmlRes = await fetch('/index.html', { credentials: 'same-origin' });
      if (htmlRes && htmlRes.ok) {
        const htmlBuffer = await htmlRes.arrayBuffer();
        const makeCleanHtml = () =>
          new Response(htmlBuffer.slice(0), {
            status: 200,
            statusText: 'OK',
            headers: {
              'Content-Type': 'text/html; charset=utf-8',
              'X-Ompagano-Cache': CACHE_NAME
            }
          });
        await cache.put('/', makeCleanHtml());
        await cache.put('/index.html', makeCleanHtml());
        await cache.put(window.location.href, makeCleanHtml());
      }
    } catch {}

    // 2. Collect and cache all JS, CSS, manifest, icons, and modules without Vary headers
    const urls = await collectAllAppAssetUrls();
    let count = 0;

    await Promise.allSettled(
      urls.map(async (rawUrl) => {
        if (rawUrl === '/' || rawUrl === '/index.html') {
          count++;
          return;
        }
        try {
          const parsed = new URL(rawUrl, window.location.origin);
          if (parsed.origin !== window.location.origin) return;

          const keyWithSearch = parsed.pathname + parsed.search;
          const keyPathname = parsed.pathname;

          const existing = await cache.match(keyWithSearch);
          if (existing && existing.ok) {
            count++;
            return;
          }

          const res = await fetch(keyWithSearch, { credentials: 'same-origin' });
          if (res && res.ok) {
            const buffer = await res.arrayBuffer();
            const contentType = resolveMimeType(keyWithSearch, res);
            const makeClean = () =>
              new Response(buffer.slice(0), {
                status: 200,
                statusText: 'OK',
                headers: {
                  'Content-Type': contentType,
                  'X-Ompagano-Cache': CACHE_NAME
                }
              });

            await cache.put(keyWithSearch, makeClean());
            if (keyPathname !== keyWithSearch) {
              await cache.put(keyPathname, makeClean());
            }
            count++;
          }
        } catch {}
      })
    );

    // 3. Instruct the Service Worker to verify and warm up any remaining URLs
    if ('serviceWorker' in navigator) {
      const reg = await navigator.serviceWorker.getRegistration('/');
      const sw = navigator.serviceWorker.controller || reg?.active || reg?.waiting || reg?.installing;
      if (sw) {
        sw.postMessage({
          type: 'WARMUP_CACHE',
          pageUrl: window.location.href,
          urls
        });
      }
    }

    updateStatus({
      isReady: true,
      isWarmingUp: false,
      cachedAssetsCount: count
    });
  } catch (err) {
    console.warn('[PWA] Warmup notice:', err);
    updateStatus({ isWarmingUp: false });
  }
}

/**
 * Registers `/sw.js` and orchestrates immediate CacheStorage warmup across all browsers
 */
export function initOfflineServiceWorker(): void {
  if (typeof window === 'undefined' || !('serviceWorker' in navigator)) return;

  const startRegistration = async () => {
    try {
      const registration = await navigator.serviceWorker.register('/sw.js', {
        scope: '/',
        updateViaCache: 'none'
      });

      await warmUpOfflineShell();

      if (registration.waiting) {
        registration.waiting.postMessage({ type: 'SKIP_WAITING' });
      }

      registration.addEventListener('updatefound', () => {
        const newWorker = registration.installing;
        if (!newWorker) return;
        newWorker.addEventListener('statechange', () => {
          if (newWorker.state === 'activated') {
            warmUpOfflineShell();
          }
        });
      });

      const readyReg = await navigator.serviceWorker.ready;
      if (readyReg.active) {
        await warmUpOfflineShell();
      }
    } catch (err) {
      console.warn('[PWA] Service Worker registration notice:', err);
      warmUpOfflineShell();
    }
  };

  navigator.serviceWorker.addEventListener('message', (event) => {
    const data = event.data;
    if (!data || typeof data !== 'object') return;
    if (data.type === 'SW_ACTIVE_AND_READY') {
      warmUpOfflineShell();
    } else if (data.type === 'WARMUP_COMPLETE') {
      updateStatus({
        isReady: true,
        isWarmingUp: false,
        cachedAssetsCount: Math.max(currentStatus.cachedAssetsCount, data.cachedCount || 0)
      });
    }
  });

  navigator.serviceWorker.addEventListener('controllerchange', () => {
    warmUpOfflineShell();
  });

  startRegistration();

  setTimeout(() => {
    warmUpOfflineShell();
  }, 1800);

  setTimeout(() => {
    warmUpOfflineShell();
  }, 4500);
}

/**
 * React hook to observe whether the app shell is cached and ready for Airplane Mode
 */
export function useOfflineShellStatus(): OfflineShellStatus {
  const [status, setStatus] = useState<OfflineShellStatus>(currentStatus);

  useEffect(() => {
    const handler: StatusListener = (next) => setStatus({ ...next });
    listeners.add(handler);
    return () => {
      listeners.delete(handler);
    };
  }, []);

  return status;
}
